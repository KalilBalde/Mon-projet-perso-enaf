create table public.listings (
  id bigint generated by default as identity (start with 1000) primary key,
  owner_id uuid not null references auth.users (id) on delete restrict,
  title text not null check (length(trim(title)) between 4 and 140),
  quartier text not null check (length(trim(quartier)) between 2 and 100),
  price bigint not null check (price > 0),
  surface numeric(10, 2) not null check (surface > 0),
  rooms integer not null default 0 check (rooms >= 0),
  bathrooms integer not null default 0 check (bathrooms >= 0),
  type text not null check (
    type in ('Appartement', 'Maison', 'Terrain-Vide', 'Chambre-Studio', 'Villa')
  ),
  is_new boolean not null default true,
  status text check (status in ('sold', 'rented')),
  image text not null check (image ~* '^https://'),
  images text[] not null default array[]::text[],
  description text not null default '' check (length(description) <= 5000),
  features text[] not null default array[]::text[],
  priority integer not null default 0,
  moderation_status text not null default 'pending'
    check (moderation_status in ('pending', 'published', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users (id) on delete set null
);

create index listings_public_order_idx
  on public.listings (created_at desc)
  where moderation_status = 'published';

create index listings_owner_created_idx
  on public.listings (owner_id, created_at desc);

alter table public.listings enable row level security;

grant select on table public.listings to anon, authenticated;
grant insert on table public.listings to authenticated;
grant usage, select on sequence public.listings_id_seq to authenticated;

create policy "Public can view published listings"
on public.listings
for select
to anon
using (moderation_status = 'published');

create policy "Authenticated users can view published and authorized listings"
on public.listings
for select
to authenticated
using (
  moderation_status = 'published'
  or owner_id = (select auth.uid())
  or coalesce(public.current_user_role(), '') in ('admin', 'super_admin')
);

create policy "Authorized roles can submit listings"
on public.listings
for insert
to authenticated
with check (
  owner_id = (select auth.uid())
  and (
    (
      public.current_user_role() = 'landlord'
      and moderation_status = 'pending'
    )
    or (
      public.current_user_role() in ('admin', 'super_admin')
      and moderation_status = 'published'
    )
  )
);

create or replace function public.review_listing_submission(
  target_listing_id bigint,
  approve_submission boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null
    or coalesce(public.current_user_role(), '') not in ('admin', 'super_admin') then
    raise exception using errcode = '42501', message = 'Not authorized';
  end if;

  update public.listings
  set moderation_status = case
        when approve_submission then 'published'
        else 'rejected'
      end,
      reviewed_at = now(),
      reviewed_by = (select auth.uid())
  where id = target_listing_id
    and moderation_status = 'pending';

  if not found then
    raise exception using errcode = '22023', message = 'No pending listing found';
  end if;
end;
$$;

revoke all on function public.review_listing_submission(bigint, boolean)
  from public, anon;
grant execute on function public.review_listing_submission(bigint, boolean)
  to authenticated;
